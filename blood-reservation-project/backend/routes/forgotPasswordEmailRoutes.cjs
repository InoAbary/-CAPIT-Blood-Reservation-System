require('dotenv').config();

const express = require('express');
const bcrypt = require('bcryptjs');
const crypto = require('node:crypto');
const { rateLimit } = require('express-rate-limit');
const { sendEmail, mailTemplate } = require('../utils/forgotPasswordEmail.cjs');
const Donor = require('../../db/models/donor.cjs');

const router = express.Router();
const TOKEN_TTL_MS = 15 * 60 * 1000;
const GENERIC_MESSAGE = 'If this email belongs to a donor account, a password reset link will be sent. Please check your inbox and spam folder.';
const INVALID_LINK = 'This password reset link is invalid or has expired. Please request a new link.';
const hashToken = token => crypto.createHash('sha256').update(token).digest('hex');

function requestLimit(limit) {
    return rateLimit({
        windowMs: TOKEN_TTL_MS,
        limit,
        standardHeaders: true,
        legacyHeaders: false,
        message: { success: false, message: 'Too many attempts. Please try again in 15 minutes.' }
    });
}

router.post('/forgotpassword', requestLimit(10), async (req, res) => {
    res.set('Cache-Control', 'no-store');
    const email = typeof req.body?.email === 'string' ? req.body.email.trim().toLowerCase() : '';
    if (!email || email.length > 254 || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
        return res.status(400).json({ success: false, message: 'Enter a valid donor email address.' });
    }
    let issuedToken;
    try {
        // Donors only: never query or modify the Staff collection.
        const donor = await Donor.findOne({ email, role: 'donor' }).select('+password');
        if (!donor || typeof donor.password !== 'string' || !donor.password) {
            return res.status(200).json({ success: true, message: GENERIC_MESSAGE });
        }
        const frontendURL = new URL(process.env.FRONTEND_URL || 'http://localhost:5173');
        if (!['http:', 'https:'].includes(frontendURL.protocol)) throw new Error('Invalid FRONTEND_URL');
        if (process.env.NODE_ENV === 'production' && frontendURL.protocol !== 'https:') throw new Error('FRONTEND_URL must use HTTPS in production');
        const token = crypto.randomBytes(32).toString('hex');
        const tokenHash = hashToken(token);
        // One outstanding reset per donor. Match the password read above so
        // a concurrent password change cannot issue a link for an older version.
        const updated = await Donor.findOneAndUpdate(
            { _id: donor._id, role: 'donor', password: donor.password },
            { $set: { passwordReset: {
                tokenHash,
                expiresAt: new Date(Date.now() + TOKEN_TTL_MS),
                                                     passwordFingerprint: hashToken(donor.password)
            } } },
            { runValidators: true }
        );
        if (!updated) return res.status(200).json({ success: true, message: GENERIC_MESSAGE });
        issuedToken = { donorID: donor._id, tokenHash };
        const link = new URL('/resetPassword', frontendURL);
        // The token identifies the donor; an editable donor ID is unnecessary.
        link.searchParams.set('token', token);
        await sendEmail({
            email: donor.email,
            subject: 'Password Reset - Philippine Red Cross Donor Account',
            message: mailTemplate(
                'We received a request to reset your donor password. This link expires in 15 minutes. Only your latest reset link will work. If you did not request this, you can ignore this email.',
                link.toString(),
                                  'Reset Password'
            ),
            text: `Reset your donor password: ${link.toString()}\nThis link expires in 15 minutes. If you did not request it, ignore this email.`
        });
        return res.status(200).json({ success: true, message: GENERIC_MESSAGE });
    } catch (error) {
        // Do not leave an unsent link usable. Do not log raw tokens or passwords.
        if (issuedToken) {
            try {
                // Never remove a newer link if an earlier email attempt fails.
                await Donor.updateOne(
                    { _id: issuedToken.donorID, 'passwordReset.tokenHash': issuedToken.tokenHash },
                    { $unset: { passwordReset: 1 } }
                );
            }
            catch { console.error('Could not remove an unsent password reset record.'); }
        }
        console.error('Donor reset email failed:', error.code || error.name);
        return res.status(503).json({ success: false, message: 'Password recovery is temporarily unavailable. Please try again later.' });
    }
});

router.post('/resetpassword', requestLimit(20), async (req, res) => {
    res.set('Cache-Control', 'no-store');
    const { password, token } = req.body || {};
    // Support links generated by this version (64 hex) and the supplied version (40 hex).
    if (typeof token !== 'string' || !/^(?:[a-f0-9]{40}|[a-f0-9]{64})$/.test(token)) {
        return res.status(400).json({ success: false, message: INVALID_LINK });
    }
    if (typeof password !== 'string' || password.length < 8 || Buffer.byteLength(password, 'utf8') > 72 || !password.trim()) {
        return res.status(400).json({ success: false, message: 'Use at least 8 characters and no more than 72 UTF-8 bytes for your new password.' });
    }
    const tokenHash = hashToken(token);
    try {
        const donor = await Donor.findOne({
            role: 'donor',
            'passwordReset.tokenHash': tokenHash,
            'passwordReset.expiresAt': { $gt: new Date() }
        }).select('+passwordReset +password');
        if (!donor || typeof donor.password !== 'string' ||
            donor.passwordReset.passwordFingerprint !== hashToken(donor.password)) {
            return res.status(400).json({ success: false, message: INVALID_LINK });
            }
            const passwordHash = await bcrypt.hash(password, 10);
        // Standalone-safe: password change AND token consumption are a single
        // atomic update to ONE donor document. Concurrent attempts cannot both
        // match after the first update removes passwordReset.
        const changed = await Donor.findOneAndUpdate(
            {
                _id: donor._id,
                role: 'donor',
                password: donor.password,
                'passwordReset.tokenHash': tokenHash,
                'passwordReset.expiresAt': { $gt: new Date() }
            },
            { $set: { password: passwordHash }, $unset: { passwordReset: 1 } },
            { runValidators: true }
        );
        if (!changed) return res.status(400).json({ success: false, message: INVALID_LINK });
        res.clearCookie('donorToken', {
            httpOnly: true,
            secure: process.env.NODE_ENV === 'production',
            sameSite: 'lax',
            path: '/'
        });
        return res.status(200).json({ success: true, message: 'Your password has been changed. Please sign in with your new password.' });
    } catch (error) {
        console.error('Donor password reset failed:', error.code || error.name);
        return res.status(500).json({ success: false, message: 'Your password could not be changed. Please try again later.' });
    }
});

module.exports = router;
